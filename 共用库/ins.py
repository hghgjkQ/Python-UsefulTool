def scroll(handle: HWND, delta: int, x: int, y: int):
    """在坐标(x, y)滚动鼠标滚轮

    Args:
        handle (HWND): 窗口句柄
        delta (int): 为正向上滚动，为负向下滚动
        x (int): 横坐标
        y (int): 纵坐标
    """
    move_to(handle, x, y)
    # https://docs.microsoft.com/en-us/windows/win32/inputdev/wm-mousewheel
    wparam = delta << 16
    p = POINT(x, y)
    ClientToScreen(handle, byref(p))
    lparam = p.y << 16 | p.x
    PostMessageW(handle, WM_MOUSEWHEEL, wparam, lparam)


def scroll_up(handle: HWND, x: int, y: int):
    """在坐标(x, y)向上滚动鼠标滚轮

    Args:
        handle (HWND): 窗口句柄
        x (int): 横坐标
        y (int): 纵坐标
    """
    scroll(handle, WHEEL_DELTA, x, y)


def scroll_down(handle: HWND, x: int, y: int):
    """在坐标(x, y)向下滚动鼠标滚轮

    Args:
        handle (HWND): 窗口句柄
        x (int): 横坐标
        y (int): 纵坐标
    """
    scroll(handle, -WHEEL_DELTA, x, y)



def 窗口截图(window_title,name,保存=True): #0.0969991683959961s
    # 获取窗口句柄
    if isinstance(window_title,int):
        hwnd=window_title
        if not hwnd:
            print(f"没有句柄'{window_title}'")
            return
    elif isinstance(window_title,str):
        hwnd = win32gui.FindWindow(None, window_title)
        if not hwnd:
            print(f"没有窗口'{window_title}'")
            return
    else:
        print('window_title类型错误')
        return

    # 获取窗口大小
    left, top, right, bottom = win32gui.GetWindowRect(hwnd)
    width = right - left
    height = bottom - top

    # 获取窗口的设备上下文
    hwndDC = win32gui.GetWindowDC(hwnd)
    mfcDC = win32ui.CreateDCFromHandle(hwndDC)
    saveDC = mfcDC.CreateCompatibleDC()

    # 创建位图对象
    saveBitMap = win32ui.CreateBitmap()
    saveBitMap.CreateCompatibleBitmap(mfcDC, width, height)
    saveDC.SelectObject(saveBitMap)

    # 使用 PrintWindow 截图
    result = windll.user32.PrintWindow(hwnd, saveDC.GetSafeHdc(), 0)
    if result != 1:
        print("截图失败！")
        return

    # 获取位图信息并转换为 PIL 图像
    bmpinfo = saveBitMap.GetInfo()
    bmpstr = saveBitMap.GetBitmapBits(True)
    img = Image.frombuffer(
        'RGB',
        (bmpinfo['bmWidth'], bmpinfo['bmHeight']),
        bmpstr, 'raw', 'BGRX', 0, 1
    )



    # 清理资源
    win32gui.DeleteObject(saveBitMap.GetHandle())
    saveDC.DeleteDC()
    mfcDC.DeleteDC()
    win32gui.ReleaseDC(hwnd, hwndDC)

    # 保存截图
    if 保存:
        img.save(name)
    return img



def 截图(name,截图范围,保存=True): #0.09299993515014648
    screenshot = ImageGrab.grab(bbox=截图范围) # 截图指定区域
    if 保存:
        # 保存截图
        screenshot.save(name)
    return screenshot

def 测时(x,t=1):
    if t==1:
        a=time.time()
        x()
        return time.time()-a
    else:
        a=time.time()
        for i in range(t):
            x()
        return (time.time()-a)/t


